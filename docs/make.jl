# Reference lists of the names accepted by the API, generated from the package and the data
function write_codes(path)
    regions = sort(available_regions(country="France"), :region_code)
    deps = sort(available_departments(country="France"), :department_code)
    species = available_species(country="France")
    open(path, "w") do io
        println(io, """
        # Species, regions and departments

        This page lists the values that can be passed as `specie` and `subregion` to
        [`estimate_growth`](@ref) and [`create_report`](@ref). Names are matched ignoring case and
        accents; regions and departments can also be given by their code. Leaving `subregion`
        empty selects the whole country.

        *This page is generated by `docs/make.jl` from the package data.*

        ## Regions (France)

        | Code | Region |
        |:-----|:-------|""")
        for r in eachrow(regions)
            println(io, "| `", r.region_code, "` | ", r.region, " |")
        end
        println(io, """

        ## Departments (France)

        | Code | Department | Region |
        |:-----|:-----------|:-------|""")
        for r in eachrow(deps)
            println(io, "| `", r.department_code, "` | ", r.department, " | ", r.region, " |")
        end
        println(io, """

        ## Species (France)

        Latin names (TAXREF) of the species found alive in the inventory, by decreasing national
        growing stock in the latest year. A binomial (e.g. `Pinus nigra`) selects all the
        subspecies and varieties starting with it.

        | Species | Plots (all years) | Growing stock, latest year (million m³) |
        |:--------|------------------:|----------------------------------------:|""")
        for r in eachrow(species)
            println(io, "| *", r.specie, "* | ", r.n_plots, " | ", round(r.vol_last_year / 1e6; digits=2), " |")
        end
    end
end
write_codes(joinpath(SRC, "codes.md"))

